'use client'

import { apiFetch, qs } from './client'
import type {
  AdminGalleryPhoto,
  AdminGalleryQuery,
  AdminOccasion,
  AdminOfferItem,
  AdminService,
  GalleryPhotoInput,
  OccasionInput,
  OfferItemInput,
  ServiceInput,
  Upload,
  UploadKind,
  AdminCreateUserInput,
  AdminUserDetail,
  AdminUserListItem,
  AdminUserListQuery,
  AdminUserUpdateInput,
  DashboardSummary,
  InviteResult,
  Page,
  User,
  AdminCreateOrderInput,
  AdminOrderListQuery,
  AdminOrderUpdateInput,
  Client,
  ClientDetail,
  ClientGooglePush,
  ClientInput,
  ClientListQuery,
  ContactMessage,
  Agenda,
  AgendaQuery,
  CalendarSyncResult,
  GoogleCalendar,
  GoogleSettingsInput,
  GoogleStatus,
  NewMessageInput,
  Order,
  OrderItemInput,
  OrderListItem,
  OrderMessage,
  PaymentInput,
  ProposalInput,
  TransitionInput,
} from './types'

/** Typed wrappers over `/admin/*`, one per route. */
export const backofficeApi = {
  dashboard: () => apiFetch<DashboardSummary>('/admin/dashboard'),
  agenda: (query: AgendaQuery) => apiFetch<Agenda>(`/admin/agenda${qs(query)}`),
  uploads: {
    upload: (file: File, kind: UploadKind, signal?: AbortSignal) => {
      const form = new FormData()
      form.append('kind', kind)
      form.append('file', file, file.name)
      return apiFetch<Upload>('/uploads', { method: 'POST', body: form, signal })
    },
  },
  occasions: {
    list: () => apiFetch<AdminOccasion[]>('/admin/occasions'),
    create: (input: OccasionInput) => apiFetch<AdminOccasion>('/admin/occasions', { method: 'POST', body: input }),
    update: (id: string, input: OccasionInput) => apiFetch<AdminOccasion>(`/admin/occasions/${id}`, { method: 'PATCH', body: input }),
    order: (ids: string[]) => apiFetch<AdminOccasion[]>('/admin/occasions/order', { method: 'PUT', body: { ids } }),
    remove: (id: string) => apiFetch<void>(`/admin/occasions/${id}`, { method: 'DELETE' }),
  },
  services: {
    list: () => apiFetch<AdminService[]>('/admin/services'),
    get: (id: string) => apiFetch<AdminService>(`/admin/services/${id}`),
    create: (input: ServiceInput) => apiFetch<AdminService>('/admin/services', { method: 'POST', body: input }),
    update: (id: string, input: ServiceInput) => apiFetch<AdminService>(`/admin/services/${id}`, { method: 'PATCH', body: input }),
    order: (ids: string[]) => apiFetch<AdminService[]>('/admin/services/order', { method: 'PUT', body: { ids } }),
    remove: (id: string) => apiFetch<void>(`/admin/services/${id}`, { method: 'DELETE' }),
    createItem: (serviceId: string, input: OfferItemInput) => apiFetch<AdminOfferItem>(`/admin/services/${serviceId}/items`, { method: 'POST', body: input }),
    orderItems: (serviceId: string, ids: string[]) => apiFetch<AdminOfferItem[]>(`/admin/services/${serviceId}/items/order`, { method: 'PUT', body: { ids } }),
  },
  items: {
    update: (id: string, input: OfferItemInput) => apiFetch<AdminOfferItem>(`/admin/items/${id}`, { method: 'PATCH', body: input }),
    remove: (id: string) => apiFetch<void>(`/admin/items/${id}`, { method: 'DELETE' }),
  },
  gallery: {
    list: (query: AdminGalleryQuery = {}) => apiFetch<AdminGalleryPhoto[]>(`/admin/gallery${qs(query)}`),
    create: (input: GalleryPhotoInput) => apiFetch<AdminGalleryPhoto>('/admin/gallery', { method: 'POST', body: input }),
    createBulk: (photos: GalleryPhotoInput[]) => apiFetch<AdminGalleryPhoto[]>('/admin/gallery/bulk', { method: 'POST', body: { photos } }),
    update: (id: string, input: GalleryPhotoInput) => apiFetch<AdminGalleryPhoto>(`/admin/gallery/${id}`, { method: 'PATCH', body: input }),
    order: (ids: string[]) => apiFetch<AdminGalleryPhoto[]>('/admin/gallery/order', { method: 'PUT', body: { ids } }),
    remove: (id: string) => apiFetch<void>(`/admin/gallery/${id}`, { method: 'DELETE' }),
  },
  users: {
    list: (query: AdminUserListQuery = {}) => apiFetch<Page<AdminUserListItem>>(`/admin/users${qs(query)}`),
    get: (id: string) => apiFetch<AdminUserDetail>(`/admin/users/${id}`),
    create: (input: AdminCreateUserInput) => apiFetch<InviteResult>('/admin/users', { method: 'POST', body: input }),
    invite: (id: string, sendEmail = true) => apiFetch<InviteResult>(`/admin/users/${id}/invite${qs({ sendEmail })}`, { method: 'POST' }),
    update: (id: string, input: AdminUserUpdateInput) => apiFetch<User>(`/admin/users/${id}`, { method: 'PATCH', body: input }),
    disable: (id: string) => apiFetch<User>(`/admin/users/${id}/disable`, { method: 'POST' }),
    enable: (id: string) => apiFetch<User>(`/admin/users/${id}/enable`, { method: 'POST' }),
    remove: (id: string) => apiFetch<void>(`/admin/users/${id}`, { method: 'DELETE' }),
  },
  orders: {
    list: (query: AdminOrderListQuery = {}) => apiFetch<Page<OrderListItem>>(`/admin/orders${qs(query)}`),
    get: (id: string) => apiFetch<Order>(`/admin/orders/${id}`),
    create: (input: AdminCreateOrderInput) => apiFetch<Order>('/admin/orders', { method: 'POST', body: input }),
    update: (id: string, input: AdminOrderUpdateInput) => apiFetch<Order>(`/admin/orders/${id}`, { method: 'PATCH', body: input }),
    transition: (id: string, input: TransitionInput) => apiFetch<Order>(`/admin/orders/${id}/transition`, { method: 'POST', body: input }),
    proposal: (id: string, input: ProposalInput) => apiFetch<Order>(`/admin/orders/${id}/proposal`, { method: 'PUT', body: input }),
    items: (id: string, items: OrderItemInput[], notifyClient = true) => apiFetch<Order>(`/admin/orders/${id}/items`, { method: 'PUT', body: { items, notifyClient } }),
    payment: (id: string, input: PaymentInput) => apiFetch<Order>(`/admin/orders/${id}/payment`, { method: 'PUT', body: input }),
    messages: (id: string) => apiFetch<OrderMessage[]>(`/admin/orders/${id}/messages`),
    sendMessage: (id: string, input: NewMessageInput) => apiFetch<OrderMessage>(`/admin/orders/${id}/messages`, { method: 'POST', body: input }),
    addAttachments: (id: string, uploadIds: string[]) => apiFetch<Order>(`/admin/orders/${id}/attachments`, { method: 'POST', body: { uploadIds } }),
    removeAttachment: (id: string, attachmentId: string) => apiFetch<void>(`/admin/orders/${id}/attachments/${attachmentId}`, { method: 'DELETE' }),
  },
  clients: {
    list: (query: ClientListQuery = {}) => apiFetch<Page<Client>>(`/admin/clients${qs(query)}`),
    get: (id: string) => apiFetch<ClientDetail>(`/admin/clients/${id}`),
    create: (input: ClientInput) => apiFetch<Client>('/admin/clients', { method: 'POST', body: input }),
    update: (id: string, input: ClientInput) => apiFetch<Client>(`/admin/clients/${id}`, { method: 'PATCH', body: input }),
    merge: (keepId: string, mergeId: string) => apiFetch<Client>('/admin/clients/merge', { method: 'POST', body: { keepId, mergeId } }),
    remove: (id: string) => apiFetch<void>(`/admin/clients/${id}`, { method: 'DELETE' }),
    pushToGoogle: (id: string) => apiFetch<ClientGooglePush>(`/admin/clients/${id}/google`, { method: 'POST' }),
    unlinkGoogle: (id: string) => apiFetch<Client>(`/admin/clients/${id}/google`, { method: 'DELETE' }),
  },
  contacts: {
    list: (query: { handled?: boolean; page?: number; limit?: number } = {}) => apiFetch<Page<ContactMessage>>(`/admin/contacts${qs(query)}`),
    setHandled: (id: string, handled: boolean) => apiFetch<ContactMessage>(`/admin/contacts/${id}/handled`, { method: 'PATCH', body: { handled } }),
    convert: (id: string) => apiFetch<Order>(`/admin/contacts/${id}/convert`, { method: 'POST' }),
    remove: (id: string) => apiFetch<void>(`/admin/contacts/${id}`, { method: 'DELETE' }),
  },
  google: {
    status: () => apiFetch<GoogleStatus>('/admin/google'),
    connectUrl: () => apiFetch<{ url: string }>('/admin/google/connect'),
    disconnect: () => apiFetch<void>('/admin/google', { method: 'DELETE' }),
    settings: (input: GoogleSettingsInput) => apiFetch<GoogleStatus>('/admin/google/settings', { method: 'PUT', body: input }),
    retryEmails: () => apiFetch<void>('/admin/google/email/retry', { method: 'POST' }),
    calendars: () => apiFetch<GoogleCalendar[]>('/admin/google/calendars'),
    resyncCalendar: () => apiFetch<CalendarSyncResult>('/admin/google/calendar/resync', { method: 'POST' }),
  },
}
